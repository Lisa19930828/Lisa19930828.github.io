// ====================== 辅助函数 ======================
function changeColor(key) { renderSelect(key); }

function renderSelect(prodKey) {
  let selDom = document.getElementById("sizeSelect");
  let priceDom = document.getElementById("unitPrice");
  if (!selDom || !priceDom) return;
  let arr = productPrice[prodKey];
  selDom.innerHTML = "";
  if (!arr || arr.length === 0) {
    let opt = new Option("Custom Size | Quote Later", "0");
    selDom.appendChild(opt);
    priceDom.textContent = "Custom Price";
    selDom.onchange = null;
    return;
  }
  arr.forEach(item => {
    let [size, price] = item.split("|");
    let opt = new Option(`${size} | ${price}`, price.replace("$", ""));
    selDom.appendChild(opt);
  });
  priceDom.textContent = arr[0].split("|")[1];
  selDom.onchange = () => priceDom.textContent = "$" + selDom.value;
}

// ====================== 添加报价（自动合并相同名称+颜色+尺寸） ======================
function addToQuote(productName) {
  let colorSel = document.getElementById("colorSelect");
  let sizeSel = document.getElementById("sizeSelect");
  let qty = +document.getElementById("qtyInput").value || 1;
  let remark = document.getElementById("customRemark")?.value || "";
  let colorTxt = colorSel.options[colorSel.selectedIndex].text;
  let sizeTxt = sizeSel.options[sizeSel.selectedIndex].text;
  let unit = Number(sizeSel.value);
  let total = unit === 0 ? "Custom" : "$" + (unit * qty).toFixed(2);
  let cart = JSON.parse(localStorage.getItem("quoteCart") || "[]");

  // 与 quote.html 显示名称保持一致
  let finalProductName = productName;
  if (productName === "Custom Mirror Product") {
    finalProductName = "Mirror Ball (Round)";
  }

  let existing = cart.find(item =>
    item.name === finalProductName &&
    item.color === colorTxt &&
    item.size === sizeTxt
  );
  if (existing) {
    existing.qty += qty;
    if (unit !== 0) existing.total = "$" + (unit * existing.qty).toFixed(2);
  } else {
    cart.push({
      name: finalProductName,
      color: colorTxt,
      size: sizeTxt,
      qty: qty,
      unit: unit === 0 ? "Custom" : "$" + unit,
      total: total,
      remark: remark
    });
  }

  localStorage.setItem("quoteCart", JSON.stringify(cart));
  alert("Added to Quote!");
}

